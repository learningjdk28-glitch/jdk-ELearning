// ---- policy helpers (owner = row belongs to the signed-in user, admin = profiles.role = 'admin') ----
const UID = '(select auth.uid())';
const ADMIN = '(select public.is_admin())';

function ownerPolicies(table, { insertCheck = `${UID} = user_id`, withDelete = true } = {}) {
  const t = `public.${table}`;
  const out = [
    `drop policy if exists "${table} select own" on ${t};`,
    `create policy "${table} select own" on ${t} for select to authenticated using (${UID} = user_id or ${ADMIN});`,
    `drop policy if exists "${table} insert own" on ${t};`,
    `create policy "${table} insert own" on ${t} for insert to authenticated with check (${insertCheck});`,
    `drop policy if exists "${table} update own" on ${t};`,
    `create policy "${table} update own" on ${t} for update to authenticated using (${UID} = user_id) with check (${UID} = user_id);`,
  ];
  if (withDelete) {
    out.push(
      `drop policy if exists "${table} delete own" on ${t};`,
      `create policy "${table} delete own" on ${t} for delete to authenticated using (${UID} = user_id);`,
    );
  }
  return out.join('\n');
}

function contentPolicies(table) {
  const t = `public.${table}`;
  return [
    `drop policy if exists "${table} read" on ${t};`,
    `create policy "${table} read" on ${t} for select to authenticated using (true);`,
    `drop policy if exists "${table} admin insert" on ${t};`,
    `create policy "${table} admin insert" on ${t} for insert to authenticated with check (${ADMIN});`,
    `drop policy if exists "${table} admin update" on ${t};`,
    `create policy "${table} admin update" on ${t} for update to authenticated using (${ADMIN}) with check (${ADMIN});`,
    `drop policy if exists "${table} admin delete" on ${t};`,
    `create policy "${table} admin delete" on ${t} for delete to authenticated using (${ADMIN});`,
  ].join('\n');
}

